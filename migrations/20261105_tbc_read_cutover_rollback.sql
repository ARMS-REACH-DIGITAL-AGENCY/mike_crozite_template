CREATE OR REPLACE VIEW public.player_hsids AS
SELECT p.playerid,
    p.firstname,
    p.lastname,
    s.hsid,
    s.hsname,
    s.hslocation
   FROM tbc_players_raw p
     LEFT JOIN tbc_schools_raw s ON regexp_replace(lower(TRIM(BOTH FROM p.high_school)), '[.\s]+'::text, ' '::text, 'g'::text) = regexp_replace(lower(TRIM(BOTH FROM s.hs_lookup_key)), '[.\s]+'::text, ' '::text, 'g'::text)
  WHERE NOT (EXISTS ( SELECT 1
           FROM player_hsid_exclusion x
          WHERE x.playerid = p.playerid AND x.hsid = s.hsid::text));

