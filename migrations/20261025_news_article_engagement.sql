-- News interactions are separate from player_moment_* because news UUIDs are
-- distinct from timeline moment IDs. This migration is NOT applied by a build.
CREATE TABLE IF NOT EXISTS public.news_article_likes (
  news_uuid text NOT NULL REFERENCES public.news_articles(uuid) ON DELETE CASCADE,
  actor_uid text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (news_uuid, actor_uid)
);
CREATE TABLE IF NOT EXISTS public.news_article_comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  news_uuid text NOT NULL REFERENCES public.news_articles(uuid) ON DELETE CASCADE,
  firebase_uid text NOT NULL,
  body text NOT NULL CHECK (length(body) BETWEEN 1 AND 2000),
  status text NOT NULL DEFAULT 'visible',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS news_article_comments_news_created_idx
  ON public.news_article_comments(news_uuid,created_at,id);
CREATE TABLE IF NOT EXISTS public.news_article_player_tags (
  news_uuid text NOT NULL REFERENCES public.news_articles(uuid) ON DELETE CASCADE,
  playerid text NOT NULL,
  tagged_by_uid text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (news_uuid,playerid)
);
CREATE INDEX IF NOT EXISTS news_article_player_tags_player_idx
  ON public.news_article_player_tags(playerid,created_at DESC);
