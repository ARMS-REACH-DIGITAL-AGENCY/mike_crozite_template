-- School splash sponsorships are deliberately separate from existing
-- microsite_sponsors (footer) and player_profile_sponsors placements.
-- A sponsor logo is stored ONCE and may be assigned to any number of schools.
-- The existing sponsor_orders record remains the commerce audit trail.
-- Safe additive migration: no writes to existing tables or seed assignments.

CREATE TABLE IF NOT EXISTS public.sponsor_brands (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  logo_url text NOT NULL,
  website_url text,
  external_partner_id text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sponsor_brands_slug_format CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  CONSTRAINT sponsor_brands_logo_url_format CHECK (logo_url ~ '^(https://|/img/)'),
  CONSTRAINT sponsor_brands_name_nonempty CHECK (length(btrim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS public.school_splash_sponsorships (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hsid text NOT NULL,
  sponsor_id bigint NOT NULL REFERENCES public.sponsor_brands(id) ON DELETE RESTRICT,
  sponsor_order_id bigint REFERENCES public.sponsor_orders(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'active',
  priority integer NOT NULL DEFAULT 0,
  starts_at timestamptz NOT NULL DEFAULT now(),
  ends_at timestamptz,
  source text NOT NULL DEFAULT 'manual',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT school_splash_sponsorships_hsid_format CHECK (hsid ~ '^[0-9]+$'),
  CONSTRAINT school_splash_sponsorships_status_check CHECK (status IN ('active', 'paused', 'cancelled')),
  CONSTRAINT school_splash_sponsorships_dates_check CHECK (ends_at IS NULL OR ends_at > starts_at),
  CONSTRAINT school_splash_sponsorships_unique_slot UNIQUE (hsid, sponsor_id, starts_at)
);

CREATE INDEX IF NOT EXISTS idx_school_splash_active_hsid
  ON public.school_splash_sponsorships (hsid, priority DESC, starts_at DESC, id DESC)
  WHERE status = 'active';

CREATE INDEX IF NOT EXISTS idx_school_splash_by_sponsor
  ON public.school_splash_sponsorships (sponsor_id, hsid);

COMMENT ON TABLE public.sponsor_brands IS
  'Reusable sponsor identity/logo: one brand can sponsor unlimited school splashes.';
COMMENT ON TABLE public.school_splash_sponsorships IS
  'Per-HSID splash sponsor assignments. Highest priority, then newest active campaign wins; optionally linked to sponsor_orders.';
