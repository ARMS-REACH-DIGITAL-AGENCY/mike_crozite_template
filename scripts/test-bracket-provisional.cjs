// Isolated regression suite: no provisional winner without full source proof,
// and backup ratification never awards a win from incomplete or locked games.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.resolve(__dirname,'..');
const source = p => fs.readFileSync(path.join(root,p),'utf8');
const sourceHelper = source('src/lib/bracket/provisionalSettlement.ts');
const compiled = ts.transpileModule(sourceHelper,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exported = {};
vm.runInNewContext(compiled,{exports:exported,Date,Number,Object});
const verified = (school) => ({rosterComplete:true,scheduleComplete:true,statLinesComplete:true,expectedGames:1,finalGames:1,pendingPlayerLines:0,...school});
const fixture = {week:1,checkedAt:'2027-02-08T05:10:00Z',snapshotId:'sha256:test-verified-week1',schools:{'5004':verified({}),'9655':verified({})}};
assert.equal(exported.hasVerifiedWeek(fixture,1,5004,9655),true);
assert.equal(exported.hasVerifiedWeek(fixture,2,5004,9655),false);
assert.equal(exported.hasVerifiedWeek({...fixture,snapshotId:''},1,5004,9655),false);
assert.equal(exported.hasVerifiedWeek({...fixture,schools:{...fixture.schools,'5004':verified({pendingPlayerLines:1})}},1,5004,9655),false);
assert.equal(exported.hasVerifiedWeek({...fixture,schools:{...fixture.schools,'5004':verified({finalGames:0})}},1,5004,9655),false);
assert.equal(exported.hasVerifiedWeek({...fixture,schools:{...fixture.schools,'5004':verified({scheduleComplete:false})}},1,5004,9655),false);
assert.equal(exported.hasVerifiedWeek({...fixture,schools:{...fixture.schools,'5004':verified({rosterComplete:false})}},1,5004,9655),false);
assert.equal(exported.hasVerifiedWeek(undefined,1,5004,9655),false);
assert.equal(exported.hasVerifiedWeek({...fixture,schools:{'5004':verified({})}},1,5004,9655),false);
const live=source('src/components/bracket/liveSeason.ts');
const prepared=source('src/lib/bracket/preparedIndex.ts');
const ui=source('src/components/bracket/schoolSeason.ts');
const sql=source('src/lib/bracket/ratifyStored.ts');
const schedule=source('vercel.json');
assert.ok(live.includes("hasVerifiedWeek(live.verifiedWeek, week, g[2], g[3])"),'Require proof for both schools');
assert.ok(live.includes("g[5] = final || earlyVerified"),'Publish provisional eighth/ninth/extra innings');
assert.ok(live.includes("g[6] = final && result.winner ?"),'Winner remains null before deadline');
assert.ok(live.includes("provisional: earlyVerified ?"),'Save snapshot with Stat Ledger');
assert.ok(prepared.includes("box->'provisional' AS provisional"),'Reader recognizes certified provisional');
assert.ok(ui.includes("status: `BOT ${last}`"),'Yellow Bottom of 9th or later');
assert.ok(ui.includes("now: i === last - 1"),'Only last provisional inning stays yellow');
assert.ok(sql.includes("m.locked_at IS NULL"),'Never alter locked final');
assert.ok(sql.includes("m.box->'provisional'->>'status' = 'verified'"),'No guessing without proof');
assert.ok(sql.includes("IN (m.home_hsid,m.away_hsid)"),'Winner must be one of two schools');
assert.ok(sql.includes("s.opening_day::date + m.week * 7 <= $3::date"),'Only after Monday 4AM AZ');
assert.ok(schedule.includes('"schedule": "*/10 * * * *"'),'Live scoring every 10 minutes');
assert.ok(schedule.includes('"schedule": "15,25 11 * * 1"'),'Independent DB-only fallback');
console.log('PASS: verified early provisional, locked winner gate, BOT ninth/extra visual state, stored-only ratification, emergency alert, 10-minute scoring.');
