// Run: node scripts/test-player-season-stats.cjs
// No database or network access; execute the endpoint with table/query fixtures.
/* eslint-disable @typescript-eslint/no-require-imports -- Standalone TypeScript endpoint regression harness. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { test } = require('node:test');
const vm = require('node:vm');
const ts = require('typescript');

const filename = path.resolve(__dirname, '../src/app/api/player-season-stats/route.ts');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2021 },
}).outputText;
const plain = value => JSON.parse(JSON.stringify(value));
const stat = (year, teamid, changes = {}) => ({
  playerid: '42', playername: 'Test Player', year, teamid,
  current_team_name: `Team ${teamid}`, level_label: 'AAA', ...changes,
});

function endpointFixture(tables, extras = {}) {
  const calls = [];
  const exports = {};
  async function query(sql, values) {
    calls.push({ sql, values: plain(values) });
    if (sql.includes('select to_regclass($1)')) {
      const name = values[0].replace(/^public\./, '');
      return { rows: [{ table_name: Object.hasOwn(tables, name) ? values[0] : null }] };
    }
    const name = sql.match(/from public\.([a-z0-9_]+) r/)?.[1];
    assert(name && Object.hasOwn(tables, name), 'Unexpected endpoint table query');
    assert.match(sql, /where r\.playerid::text = \$1/);
    let rows = tables[name].filter(row => String(row.playerid) === values[0]);
    // Apply the predicate actually generated by the endpoint. Removing it
    // returns the mixed seasons and makes the duplicate regression fail.
    if (sql.includes('r.year::text = $3::text')) {
      assert.equal(values.length, 3);
      rows = rows.filter(row => row.year !== null && String(row.year) === values[2]);
    } else {
      assert.equal(values.length, 2);
    }
    return { rows: rows.map(row => ({ ...row, _source: values[1] })) };
  }
  vm.runInNewContext(compiled, {
    exports,
    console,
    require(name) {
      if (name === '@/lib/db') return { query };
      if (name === 'next/server') return {
        NextResponse: { json: (body, options = {}) => ({ body: plain(body), status: options.status || 200 }) },
      };
      if (name === '@/lib/externalStats') return {
        getRecentExternalStatsForPlayer: async () => extras.external || [],
      };
      if (name === '@/lib/indyIscore') return {
        getIndyIscoreStatsForPlayer: async () => extras.indy || { batting: [], pitching: [], recentGames: [] },
      };
      throw new Error('Unexpected endpoint dependency: ' + name);
    },
  }, { filename });
  return {
    calls,
    get: (parameters = 'playerId=42') => exports.GET({ nextUrl: new URL('https://fixture.invalid/api/player-season-stats?' + parameters) }),
  };
}

test('archived 2025 plus a held mixed current table returns each season once for batting and pitching', async () => {
  const history = [stat('2025', '100', { ab: '50', w: '3' }), stat('2026', '200', { ab: '1', w: '0' })];
  const heldCurrent = [stat('2025', '100', { ab: '50', w: '3' }), stat('2026', '200', { ab: '80', w: '5' })];
  const endpoint = endpointFixture({
    tbc_batting_raw: history, tbc_batting_2026_season_raw: heldCurrent,
    tbc_pitching_raw: history, tbc_pitching_2026_season_raw: heldCurrent,
  });
  const result = await endpoint.get();
  assert.equal(result.status, 200);
  for (const kind of ['batting', 'pitching']) {
    assert.deepEqual(result.body[kind].map(row => [row.year, row.source]), [
      ['2025', `tbc_${kind}_raw`], ['2026', `tbc_${kind}_2026_season_raw`],
    ]);
    assert.equal(result.body.counts[kind + 'Historical'], 1);
    assert.equal(result.body.counts[kind + '2026'], 1);
    assert.equal(result.body.counts[kind + 'Historical2026Excluded'], 1);
  }
  assert.equal(result.body.batting[1].ab, '80');
  assert.equal(result.body.pitching[1].w, '5');
  const currentQueries = endpoint.calls.filter(call => /from public\.tbc_(batting|pitching)_2026_season_raw r/.test(call.sql));
  assert.equal(currentQueries.length, 2);
  for (const call of currentQueries) {
    assert.match(call.sql, /r\.year::text = \$3::text/);
    assert.equal(call.values[2], '2026');
  }
  const historyQueries = endpoint.calls.filter(call => /from public\.tbc_(batting|pitching)_raw r/.test(call.sql));
  assert(historyQueries.every(call => call.values.length === 2 && !call.sql.includes('$3')));
});

test('current tables match only the exact canonical 2026 year used by resolved views', async () => {
  const years = ['2026', '2025', '2027', '2026.0', ' 2026', '2026 ', '', null];
  const rows = years.map((year, index) => stat(year, String(100 + index)));
  const endpoint = endpointFixture({
    tbc_batting_raw: [], tbc_pitching_raw: [],
    tbc_batting_2026_season_raw: rows, tbc_pitching_2026_season_raw: rows,
  });
  const result = await endpoint.get();
  assert.equal(result.status, 200);
  for (const kind of ['batting', 'pitching']) {
    assert.deepEqual(result.body[kind].map(row => [row.year, row.teamid]), [['2026', '100']]);
  }
});

test('historical fallback, expected-name filtering, external games and Indy season merging are preserved', async () => {
  const endpoint = endpointFixture({
    tbc_batting_raw: [stat('2025', '100'), stat(null, '101'), stat('2025', '102', { playername: 'Someone Else' })],
    tbc_batting_2026_season_raw: [stat('2026', '200'), stat('2026', '201', { playername: 'Someone Else' })],
    tbc_pitching_raw: [], tbc_pitching_2026_season_raw: [],
  }, {
    external: [{ source_system: 'alpb', season_year: 2026, team_identifier: '300', source_game_guid: 'game-1', stats: { h: 2 } }],
    indy: {
      batting: [
        { source: 'indy', year: '2025', teamid: '100', team: 'Team 100' },
        { source: 'indy', year: '2024', teamid: '400', team: 'Indy Club' },
      ],
      pitching: [],
      recentGames: [{ source: 'indy', year: '2026', game: 'game-2' }],
    },
  });
  const result = await endpoint.get('playerId=42&playerName=Test+Player');
  assert.equal(result.status, 200);
  assert.deepEqual(result.body.batting.map(row => [row.year, row.teamid]), [
    ['', '101'], ['2024', '400'], ['2025', '100'], ['2026', '200'],
  ]);
  assert.equal(result.body.counts.filteredOutNameMismatches, 2);
  assert.equal(result.body.counts.battingHistorical, 2);
  assert.equal(result.body.counts.indyIscoreBatting, 2);
  assert.deepEqual(result.body.externalRecentStats.map(row => row.game), ['game-1', 'game-2']);
  assert.equal(result.body.externalRecentStats[0].h, 2);
});
