'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const src = fs.readFileSync(path.resolve(__dirname, '../src/lib/storyAssets.ts'),'utf8');
const js = ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2021}}).outputText;
const mod={exports:{}};
vm.runInNewContext(js,{exports:mod.exports,process:{env:{}},encodeURIComponent});
const url=mod.exports.storyAssetUrl;
const base='https://yatstats-assets.s3.us-west-2.amazonaws.com/';
assert.equal(url('teams/21.png'),base+'teams/37.png');
assert.equal(url('teams-web/21.webp'),base+'teams-web/37.webp');
assert.equal(url('teams/37.png'),base+'teams/37.png');
assert.equal(url('teams-web/37.webp'),base+'teams-web/37.webp');
assert.equal(url('teams/10011.png'),base+'teams/10011.png');
assert.equal(url('teams/21.jpg'),base+'teams/21.jpg');
assert.equal(url('players/21.png'),base+'players/21.png');
assert.equal(url(null),null);
console.log('PASS Athletics Draft Day logo alias is limited to two verified story assets');
